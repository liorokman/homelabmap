#!/usr/bin/env python3
"""Generate internal/web/static/icons.js from pinned npm packages.

Usage: genicons.py <dir with extracted @tabler/icons@3.50.0> <dir with simple-icons@16.36.0> > icons.js
Tabler icons: MIT. Simple Icons: CC0-1.0 (brand logos remain trademarks of their owners).
"""
import json, re, sys

tabler, simple = sys.argv[1], sys.argv[2]

TABLER = {  # key -> tabler outline icon
    "router": "router", "ap": "access-point", "windows": "brand-windows", "printer": "printer",
    "media": "device-tv", "iot": "cpu", "phone": "device-mobile", "nas": "database", "server": "server",
    "camera": "device-cctv", "gaming": "device-gamepad", "unknown": "help",
}
SIMPLE = {  # key -> simple-icons slug
    "proxmox": "proxmox", "linux": "linux", "debian": "debian", "ubuntu": "ubuntu", "alpine": "alpinelinux",
    "raspberrypi": "raspberrypi", "apple": "apple", "android": "android", "freebsd": "freebsd",
    "homeassistant": "homeassistant",
}
# A network switch: chassis with ports (no suitable icon in either set).
CUSTOM = {"switch": ('<rect x="2" y="7" width="20" height="10" rx="2"/>'
                     '<path d="M6 12h.01M9.5 12h.01M13 12h.01M16.5 12h.01M6 15.5h12"/>')}

out = {}
for key, name in TABLER.items():
    svg = open(f"{tabler}/package/icons/outline/{name}.svg").read()
    body = re.sub(r'<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', "", svg)
    body = re.search(r">(.*)</svg>", body, re.S).group(1)
    out[key] = {"mode": "stroke", "body": re.sub(r"\s+", " ", body).strip()}
for key, body in CUSTOM.items():
    out[key] = {"mode": "stroke", "body": body}
for key, slug in SIMPLE.items():
    svg = open(f"{simple}/package/icons/{slug}.svg").read()
    out[key] = {"mode": "fill", "body": re.search(r"(<path[^>]*/>)", svg).group(1)}

print("// Generated by tools/genicons.py from @tabler/icons@3.50.0 (MIT) and simple-icons@16.36.0 (CC0-1.0).")
print("// Do not edit by hand.")
print("export const ICONS = " + json.dumps(out, indent=1, sort_keys=True) + ";")
